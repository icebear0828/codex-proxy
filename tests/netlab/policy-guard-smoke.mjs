/**
 * Local end-to-end smoke test for the safety-policy guard (policy_guard).
 *
 * Boots an isolated proxy instance plus the netlab mock upstream and drives the
 * exact chain the guard must protect:
 *
 *   1. turn 1 reaches the upstream once and the rejection is relayed,
 *   2. turn 2 of the same conversation is refused locally (HTTP 400) and the
 *      mock sees no second request,
 *   3. the admission is listed by the admin API and can be released from it,
 *   4. after the release, the conversation reaches the upstream again,
 *   5. the settings API round-trips a custom error-code list and persists it.
 *
 * Isolation: everything runs out of a temp runtime directory (its own config/
 * and data/), so the developer's real accounts, api keys and data/ are never
 * touched. The guard is enabled in that runtime's local.yaml — mirroring what
 * the settings page writes, without touching the repo's data/local.yaml.
 *
 * Usage:
 *   node tests/netlab/policy-guard-smoke.mjs [--keep] [--port 8199] [--mock-port 18445]
 *     --keep   leave the runtime dir on disk and print its path
 */

import { spawn, spawnSync } from "node:child_process";
import {
  cpSync, mkdirSync, mkdtempSync, openSync, readFileSync, rmSync, statSync,
  writeFileSync, existsSync, readdirSync,
} from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, "..", "..");

const args = process.argv.slice(2);
const keep = args.includes("--keep");
const argValue = (name, fallback) => {
  const idx = args.indexOf(name);
  return idx !== -1 && args[idx + 1] ? args[idx + 1] : fallback;
};

const PROXY_PORT = Number(argValue("--port", "8199"));
const MOCK_PORT = Number(argValue("--mock-port", "18445"));
const PROXY_URL = `http://127.0.0.1:${PROXY_PORT}`;
const MOCK_URL = `http://127.0.0.1:${MOCK_PORT}`;
const PROXY_API_KEY = "policy-smoke-key";
const MODEL = "netlab-mock";

// The built-in default code list must recognise this without any configuration
// — it is the relay's own constant (sub2api), which is what a real rejection
// carries (see src/proxy/policy-rejection.ts).
const REJECT_CODE = "session_blocked_by_cyber_policy";
const REJECT_MESSAGE =
  "该会话已被网络安全策略屏蔽，请开启新会话 / This session is blocked by cyber-security policy, please start a new session";
const CONVERSATION_INPUT = "walk me through this exploit proof of concept";

const results = [];
function check(name, ok, detail = "") {
  results.push({ name, ok, detail });
  console.log(`${ok ? "  ✅" : "  ❌"} ${name}${detail ? ` — ${detail}` : ""}`);
}

// ── runtime dir ───────────────────────────────────────────────────

/**
 * The native rustls addon is what the proxy uses for the upstream leg, and the
 * generated loader (native/index.js) picks its binding by target triple — a
 * checkout that only carries a differently-built `.node` fails to load. Probe
 * the candidate directories and mirror the first one that actually loads, so
 * the smoke test runs against whatever build this working tree has.
 */
function resolveNativeSource() {
  const candidates = [
    path.join(REPO, "native"),
    // Packaged Electron build: carries the platform binding this loader
    // expects even when the dev checkout was built for another target.
    path.join(REPO, "packages", "electron", "release", "win-unpacked", "resources", "native"),
  ];
  for (const dir of candidates) {
    const loader = path.join(dir, "index.js");
    if (!existsSync(loader)) continue;
    const probe = spawnSync(process.execPath, ["-e", `require(${JSON.stringify(loader)})`], {
      windowsHide: true,
      timeout: 20_000,
      stdio: "ignore",
    });
    if (probe.status === 0) return dir;
  }
  return null;
}

function prepareRuntime() {
  const dir = mkdtempSync(path.join(os.tmpdir(), "codex-policy-smoke-"));
  mkdirSync(path.join(dir, "config"), { recursive: true });
  mkdirSync(path.join(dir, "data"), { recursive: true });
  cpSync(path.join(REPO, "config"), path.join(dir, "config"), { recursive: true });

  const nativeSource = resolveNativeSource();
  const nativeLink = path.join(dir, "native");
  if (nativeSource) {
    mkdirSync(nativeLink, { recursive: true });
    for (const f of readdirSync(nativeSource)) {
      if (f.endsWith(".node") || ["index.js", "index.d.ts", "package.json", "patch-loader.mjs"].includes(f)) {
        cpSync(path.join(nativeSource, f), path.join(nativeLink, f));
      }
    }
    console.log(`[smoke] native transport: ${nativeSource}`);
  } else {
    console.warn("[smoke] no loadable native addon found — the proxy will fail to start "
      + "(build it with `cd native && npm run build`)");
  }

  writeFileSync(path.join(dir, "data", "local.yaml"), [
    "# Generated by tests/netlab/policy-guard-smoke.mjs — isolated runtime.",
    "server:",
    `  port: ${PROXY_PORT}`,
    `  proxy_api_key: "${PROXY_API_KEY}"`,
    "auth:",
    "  request_interval_ms: 0",
    "# Same field the settings page writes; the guard ships disabled.",
    "policy_guard:",
    "  enabled: true",
    "",
  ].join("\n"), "utf8");

  // One API-key upstream pointing straight at the mock (no toxiproxy here:
  // the guard is upstream-agnostic, so the direct path is all that is needed).
  writeFileSync(path.join(dir, "data", "api-keys.json"), JSON.stringify({
    keys: [{
      id: "smoke-mock-1",
      provider: "custom",
      model: MODEL,
      apiKey: "smoke",
      baseUrl: MOCK_URL,
      label: "policy-smoke-mock",
      wire: "codex-responses",
      status: "active",
      addedAt: new Date().toISOString(),
      lastUsedAt: null,
    }],
  }, null, 2), "utf8");

  return dir;
}

// ── processes ─────────────────────────────────────────────────────

async function waitHealthy(url, timeoutMs, label) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const res = await fetch(`${url}/health`, { signal: AbortSignal.timeout(1500) });
      if (res.ok) return;
    } catch { /* not up yet */ }
    await new Promise((r) => setTimeout(r, 300));
  }
  throw new Error(`${label} did not become healthy at ${url} within ${timeoutMs}ms`);
}

function killTree(child) {
  if (!child) return;
  child.kill();
  if (process.platform === "win32") {
    spawnSync("taskkill", ["/PID", String(child.pid), "/T", "/F"], { windowsHide: true });
  }
}

// ── requests ──────────────────────────────────────────────────────

/** Send one streaming turn and report what came back over the wire. */
async function sendTurn({ timeoutMs = 30000 } = {}) {
  const out = { status: null, sawCompleted: false, sawFailed: false, failureCode: null, failureMessage: null };
  const res = await fetch(`${PROXY_URL}/v1/responses`, {
    method: "POST",
    headers: {
      "content-type": "application/json",
      authorization: `Bearer ${PROXY_API_KEY}`,
    },
    body: JSON.stringify({
      model: MODEL,
      stream: true,
      input: [{ role: "user", type: "message", content: CONVERSATION_INPUT }],
    }),
    signal: AbortSignal.timeout(timeoutMs),
  });
  out.status = res.status;
  const text = await res.text();
  for (const block of text.split("\n\n")) {
    let type = null;
    let data = "";
    for (const line of block.split("\n")) {
      if (line.startsWith("event: ")) type = line.slice(7).trim();
      else if (line.startsWith("data: ")) data += line.slice(6);
    }
    if (!type) continue;
    if (type === "response.completed") out.sawCompleted = true;
    if (type === "response.failed" || type === "error") {
      out.sawFailed = true;
      try {
        const parsed = JSON.parse(data);
        const err = parsed.error ?? parsed.response?.error ?? {};
        out.failureCode = err.code ?? type;
        out.failureMessage = String(err.message ?? "").slice(0, 120);
      } catch {
        out.failureCode = type;
      }
    }
  }
  return out;
}

async function mockRequestCount() {
  const res = await fetch(`${MOCK_URL}/__stats`, { signal: AbortSignal.timeout(3000) });
  return (await res.json()).requests;
}

async function admin(pathname, init = {}) {
  const res = await fetch(`${PROXY_URL}${pathname}`, {
    ...init,
    headers: {
      authorization: `Bearer ${PROXY_API_KEY}`,
      ...(init.body ? { "content-type": "application/json" } : {}),
      ...(init.headers ?? {}),
    },
    signal: AbortSignal.timeout(5000),
  });
  return { status: res.status, body: await res.json().catch(() => null) };
}

// ── main ──────────────────────────────────────────────────────────

let runtimeDir = "";
let proxy = null;
let mock = null;

async function main() {
  runtimeDir = prepareRuntime();
  console.log(`[smoke] isolated runtime: ${runtimeDir}`);

  mock = spawn(process.execPath, [path.join(HERE, "mock-upstream.mjs")], {
    env: {
      ...process.env,
      PORT: String(MOCK_PORT),
      MOCK_EVENTS: "2",
      MOCK_POLICY_REJECT_CODE: REJECT_CODE,
      MOCK_POLICY_REJECT_MESSAGE: REJECT_MESSAGE,
    },
    stdio: "ignore",
    windowsHide: true,
  });
  await waitHealthy(MOCK_URL, 15_000, "mock upstream");

  const env = { ...process.env };
  for (const k of ["HTTP_PROXY", "HTTPS_PROXY", "ALL_PROXY", "http_proxy", "https_proxy", "all_proxy"]) {
    delete env[k];
  }
  const logPath = path.join(runtimeDir, "proxy.log");
  const logFd = openSync(logPath, "w");
  proxy = spawn(
    process.execPath,
    [path.join(REPO, "node_modules", "tsx", "dist", "cli.mjs"), path.join(REPO, "src", "index.ts")],
    { cwd: runtimeDir, env, stdio: ["ignore", logFd, logFd], windowsHide: true },
  );
  await waitHealthy(PROXY_URL, 90_000, "proxy");
  console.log(`[smoke] proxy up at ${PROXY_URL} (log: ${logPath})`);

  console.log("\n1) first turn — the upstream rejection is relayed, exactly one upstream request");
  const turn1 = await sendTurn();
  const afterTurn1 = await mockRequestCount();
  check("turn 1 relayed the terminal rejection frame", turn1.sawFailed, `code=${turn1.failureCode}`);
  check("turn 1 reached the upstream exactly once", afterTurn1 === 1, `mock requests=${afterTurn1}`);

  console.log("\n2) second turn — same conversation, must be refused locally");
  const turn2 = await sendTurn();
  const afterTurn2 = await mockRequestCount();
  check("turn 2 was refused with HTTP 400", turn2.status === 400, `status=${turn2.status}`);
  check("turn 2 never reached the upstream", afterTurn2 === afterTurn1, `mock requests=${afterTurn2}`);

  console.log("\n3) admin API — the conversation is listed and can be released");
  const listed = await admin("/admin/policy-guard-quarantines");
  const entries = listed.body?.quarantines ?? [];
  check("guard reports itself enabled", listed.body?.enabled === true);
  check("quarantine list has exactly one conversation", entries.length === 1,
    entries.map((e) => `${e.conversation_id.slice(0, 8)}:${e.code}`).join(", "));
  const released = await admin("/admin/policy-guard-quarantines/reset", {
    method: "POST",
    body: JSON.stringify({ all: true }),
  });
  check("release-all returned ok", released.body?.success === true, JSON.stringify(released.body));

  console.log("\n4) third turn — released, so it reaches the upstream again");
  const turn3 = await sendTurn();
  const afterTurn3 = await mockRequestCount();
  check("turn 3 was sent upstream again", afterTurn3 === afterTurn2 + 1,
    `mock requests=${afterTurn3}`);
  check("turn 3 relayed the rejection (upstream still refuses)", turn3.sawFailed,
    `code=${turn3.failureCode}`);
  // Released + re-rejected: the guard must have re-quarantined the conversation.
  const relisted = await admin("/admin/policy-guard-quarantines");
  check("the re-rejection was quarantined again",
    (relisted.body?.quarantines ?? []).length === 1);

  console.log("\n5) settings API — a custom error-code list round-trips");
  const saved = await admin("/admin/policy-guard-settings", {
    method: "POST",
    body: JSON.stringify({ enabled: true, error_codes: [REJECT_CODE, "smoke_custom_code"] }),
  });
  check("settings POST accepted", saved.status === 200, `status=${saved.status}`);
  const readBack = await admin("/admin/policy-guard-settings");
  const codes = readBack.body?.error_codes ?? [];
  check("custom code list persisted", codes.includes("smoke_custom_code"), JSON.stringify(codes));

  const failed = results.filter((r) => !r.ok);
  console.log(`\n[smoke] ${results.length - failed.length}/${results.length} checks passed`);
  if (failed.length > 0) {
    console.log("[smoke] proxy log tail:");
    console.log(readTail(logPath));
    return 1;
  }
  return 0;
}

function readTail(file, maxBytes = 4000) {
  try {
    const size = statSync(file).size;
    const buf = readFileSync(file);
    return buf.subarray(Math.max(0, size - maxBytes)).toString("utf8");
  } catch {
    return "(no proxy log)";
  }
}

let exitCode = 1;
try {
  exitCode = await main();
} catch (err) {
  console.error(`[smoke] failed: ${err instanceof Error ? err.stack ?? err.message : String(err)}`);
} finally {
  killTree(proxy);
  killTree(mock);
  await new Promise((r) => setTimeout(r, 300));
  if (keep && runtimeDir && existsSync(runtimeDir)) {
    console.log(`[smoke] kept runtime dir: ${runtimeDir}`);
  } else if (runtimeDir && existsSync(runtimeDir)) {
    rmSync(runtimeDir, { recursive: true, force: true });
  }
}
process.exit(exitCode);
